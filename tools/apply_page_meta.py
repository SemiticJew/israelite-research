#!/usr/bin/env python3
"""Fill in missing search and sharing metadata on the hand-written pages.

For every public page (top-level pages, articles, authors, Ologies, Good Tree collections and
study guides) this adds — only when absent —

  * <link rel="canonical"> to the page's own https://semiticjew.org URL (index.html → "/");
  * <meta name="description">, taken from the page's existing og:description or, failing that,
    the page's own lede sentence (never newly written text);
  * Open Graph and X (Twitter) card tags built from the page's <title>, description and URL,
    with the site's existing social preview image.

Existing tags are never changed, so curated article titles, images and dates stay as they are.
Redirect stubs, noindex pages (e.g. the order confirmation), the 404/offline pages, templates and generated Scripture pages are skipped
(the Scripture pages get the same tags from tools/build_scripture_pages.py).

    python3 tools/apply_page_meta.py           # write
    python3 tools/apply_page_meta.py --check   # exit 1 if a page is missing metadata
"""
import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://semiticjew.org"
SHARE_IMAGE = SITE + "/images/social-preview.png"
SKIP = {"404.html", "offline.html", "articles/article-template.html"}
GLOBS = ["*.html", "articles/*.html", "authors/*.html", "ologies/*.html", "collections/*.html", "study-guides/*.html"]
GENERATED_MARK = "Generated by tools/build_scripture_pages.py"
LEDE = re.compile(r'<p[^>]*class="[^"]*\b(?:rs-lede|in-lede|[a-z-]*subtitle|sub)\b[^"]*"[^>]*>(.*?)</p>', re.S)


def text(s):
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", s))).strip()


def attr(s):
    return html.escape(s, quote=True)


def pages():
    seen = set()
    for g in GLOBS:
        for f in sorted(ROOT.glob(g)):
            rel = f.relative_to(ROOT).as_posix()
            if rel in seen or rel in SKIP:
                continue
            seen.add(rel)
            yield rel, f


def is_redirect(s):
    return 'http-equiv="refresh"' in s


def url_for(rel):
    return SITE + "/" if rel == "index.html" else f"{SITE}/{rel}"


def meta_content(s, pattern):
    m = re.search(pattern, s)
    return html.unescape(m.group(1)) if m else None


def apply(rel, s):
    if is_redirect(s) or GENERATED_MARK in s or re.search(r'name="robots"[^>]*noindex', s):
        return s
    head_end = s.index("</head>")
    head = s[:head_end]
    title_m = re.search(r"<title>(.*?)</title>", head, re.S)
    title = text(title_m.group(1)) if title_m else ""
    desc = meta_content(head, r'<meta\s+name="description"\s+content="([^"]*)"') or meta_content(head, r'<meta\s+content="([^"]*)"\s+name="description"')
    og_desc = meta_content(head, r'<meta\s+property="og:description"\s+content="([^"]*)"')
    add = []
    if 'rel="canonical"' not in head:
        add.append(f'<link rel="canonical" href="{attr(url_for(rel))}"/>')
    if desc is None:
        desc = og_desc
        if not desc:
            m = LEDE.search(s)
            desc = text(m.group(1)) if m else ""
        if desc:
            add.append(f'<meta name="description" content="{attr(desc)}"/>')
    if 'property="og:title"' not in head and title:
        og = [f'<meta property="og:type" content="website"/>',
              f'<meta property="og:site_name" content="Semitic Jew"/>',
              f'<meta property="og:title" content="{attr(title)}"/>',
              f'<meta property="og:url" content="{attr(url_for(rel))}"/>']
        if desc:
            og.append(f'<meta property="og:description" content="{attr(desc)}"/>')
        if 'property="og:image"' not in head:
            og.append(f'<meta property="og:image" content="{SHARE_IMAGE}"/>')
        add += og
    if 'name="twitter:card"' not in head and title:
        tw = ['<meta name="twitter:card" content="summary_large_image"/>', f'<meta name="twitter:title" content="{attr(title)}"/>']
        if desc:
            tw.append(f'<meta name="twitter:description" content="{attr(desc)}"/>')
        if 'name="twitter:image"' not in head:
            img = meta_content(head, r'<meta\s+property="og:image"\s+content="([^"]*)"') or SHARE_IMAGE
            tw.append(f'<meta name="twitter:image" content="{attr(img)}"/>')
        add += tw
    if not add:
        return s
    block = "<!-- page-meta (added by tools/apply_page_meta.py) -->\n" + "\n".join(add) + "\n"
    return s[:head_end] + block + s[head_end:]


def main():
    check = "--check" in sys.argv
    changed = []
    for rel, f in pages():
        s = f.read_text(encoding="utf-8")
        new = apply(rel, s)
        if new != s:
            changed.append(rel)
            if not check:
                f.write_text(new, encoding="utf-8")
    if check:
        if changed:
            print("Missing metadata: " + ", ".join(changed))
            sys.exit(1)
        print("All pages have canonical, description and sharing metadata.")
    else:
        print(f"Updated {len(changed)} page(s): {', '.join(changed) or 'none'}")


if __name__ == "__main__":
    main()
