#!/usr/bin/env python3
"""Generate the Biblia hub, the three collection hubs and all 81 book pages.

    python3 tools/build_scripture_pages.py          # write the pages
    python3 tools/build_scripture_pages.py --check  # exit 1 if any page is out of date

Content (titles, descriptions, writer/date/audience/category, canon groups, eras, abbreviations,
breadcrumbs, links) comes only from tools/scripture_pages_content.json, which was extracted verbatim
from the previous pages by tools/extract_scripture_pages.py. Chapter availability is read from
data/<canon>/ (read only). URLs, chapter links and the collection organisation are unchanged.
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = json.loads((ROOT / "tools" / "scripture_pages_content.json").read_text(encoding="utf-8"))
CANON_LABEL = {"tanakh": "Tanakh", "newtestament": "New Testament", "apocrypha": "Apocrypha"}
# Chapter links use the page's own slug (as before); the reader normalises "psalms" to its data folder "psalm".
DATA_ALIAS = {("tanakh", "psalms"): "psalm"}
# Chapter links that existed before this generator and must keep working even though the page's own
# "Chapters" fact is lower (the old grid linked Baruch 1–6; the KJV numbers the Letter of Jeremiah as Baruch 6).
LEGACY_LINK_COUNT = {"apocrypha/baruch": 6}

e = lambda s: html.escape(str(s), quote=True)


def slugify(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def safe_abbr(s):
    """Abbreviations may contain <sup>n</sup> (e.g. <sup>1</sup>Sa); everything else is escaped."""
    parts = re.split(r"(<sup>\d</sup>)", s)
    return "".join(p if re.fullmatch(r"<sup>\d</sup>", p) else e(p) for p in parts)


def chapters_with_text(canon, slug, total):
    folder = ROOT / "data" / canon / DATA_ALIAS.get((canon, slug), slug)
    return {n for n in range(1, total + 1) if (folder / f"{n}.json").exists()}


def head(title, description, extra_css=""):
    desc = f'\n<meta name="description" content="{e(description)}"/>' if description else ""
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8"/>
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"/>
<title>{e(title)}</title>{desc}
<script>/* Apply the saved theme before first paint (same key as /js/theme-toggle.js) */try{{var t=localStorage.getItem("theme");if(t==="dark"||t==="light")document.documentElement.setAttribute("data-theme",t)}}catch(e){{}}</script>
<link rel="stylesheet" href="/styles.css"/>
<link rel="stylesheet" href="/css/sj-tokens.css"/>
<link rel="stylesheet" href="/css/scripture-pages.css"/>
<link rel="icon" type="image/x-icon" href="/favicon.ico"/>
<link rel="icon" type="image/png" sizes="16x16" href="/favicon-16x16.png"/>
<link rel="icon" type="image/png" sizes="32x32" href="/favicon-32x32.png"/>
<link rel="apple-touch-icon" sizes="180x180" href="/apple-touch-icon.png"/>
<link rel="manifest" href="/site.webmanifest"/>
<meta name="theme-color" content="#FBF8F3" media="(prefers-color-scheme: light)"/>
<meta name="theme-color" content="#0A1322" media="(prefers-color-scheme: dark)"/>
<!-- Generated by tools/build_scripture_pages.py from tools/scripture_pages_content.json — edit those, not this file. -->
</head>"""


def crumbs(items):
    out = []
    for i, c in enumerate(items):
        if i:
            out.append('<span class="sep" aria-hidden="true">›</span>')
        if "href" in c:
            out.append(f'<a href="{e(c["href"])}">{e(c["label"])}</a>')
        else:
            out.append(f'<span class="current" aria-current="page">{e(c["label"])}</span>')
    return f'<nav class="breadcrumbs sp-crumbs" aria-label="Breadcrumb">{"".join(out)}</nav>'


def page(body_attrs, title, description, main_html):
    return f"""{head(title, description)}
<body class="sj-scripture" {body_attrs}>
<a class="sp-skip" href="#main">Skip to content</a>
<div id="site-header"></div>

<main class="sp" id="main">
{main_html}
</main>

<div id="site-footer"></div>
<script src="/js/include.js" defer></script>
<script src="/js/scripture-pages.js" defer></script>
</body>
</html>
"""


# ---------------------------------------------------------------- collections model
def book_key_from_href(href):
    return href.strip("/").removesuffix(".html")


def collection(canon):
    """Groups in canon order: each guide card with its books (books keep the hub's order)."""
    hub = CONTENT["hubs"][canon]
    order, books = [], []
    for col in hub["columns"]:
        for card in col:
            if card["group"] not in order:
                order.append(card["group"])
            books.append(card)
    groups = []
    for i, g in enumerate(hub["guide"]):
        cls = order[i] if i < len(order) else None
        groups.append({**g, "books": [b for b in books if b["group"] == cls] if cls else []})
    return groups, books


def book_meta(key):
    b = CONTENT["books"][key]
    facts = {f["label"]: f["value"] for f in b["identity"]}
    total = int(re.sub(r"\D", "", facts.get("Chapters", "0")) or 0)
    return b, facts, total


# ---------------------------------------------------------------- book pages
def render_book(key, prev_card, next_card, group_title):
    b, facts, total = book_meta(key)
    canon, slug, name = b["canon"], b["slug"], b["h1"]
    total = max(total, LEGACY_LINK_COUNT.get(key, 0))
    have = chapters_with_text(canon, slug, total)
    missing = [n for n in range(1, total + 1) if n not in have]
    first = min(have) if have else 1
    href = lambda n: f"/{canon}/chapter.html?book={slug}&ch={n}"

    cells = []
    for n in range(1, total + 1):
        if n in have:
            cells.append(f'<li><a href="{href(n)}" aria-label="{e(name)} chapter {n}" data-ch="{n}">{n}</a></li>')
        else:
            cells.append(f'<li><a href="{href(n)}" class="is-unavailable" aria-label="{e(name)} chapter {n} (text not yet in the reader)" title="Text not yet in the reader" data-ch="{n}">{n}</a></li>')

    if missing and len(missing) == total:
        notice = (f'<p class="sp-notice" role="note">The text of {e(name)} isn’t in the {e(CANON_LABEL[canon])} reader yet. '
                  f'The chapter links below are kept so they work as soon as it is added.</p>')
    elif missing:
        ch = ", ".join(str(n) for n in missing)
        notice = (f'<p class="sp-notice" role="note">Chapter{"s" if len(missing) > 1 else ""} {ch} of {e(name)} '
                  f'{"are" if len(missing) > 1 else "is"} not yet in the reader; {"they are" if len(missing) > 1 else "it is"} marked below.</p>')
    else:
        notice = ""

    start = (f'<a class="sp-btn is-primary" href="{href(first)}">Start reading <span class="sp-btn-sub">{e(name)} {first}</span></a>'
             if have else f'<a class="sp-btn" href="{href(1)}">Open chapter 1</a>')

    facts_html = "".join(f'<div class="sp-fact"><dt>{e(f["label"])}</dt><dd>{e(f["value"])}</dd></div>' for f in b["identity"])

    def nav_link(card, rel, word):
        if not card:
            return f'<span class="sp-booknav-{rel} is-empty"></span>'
        return (f'<a class="sp-booknav-{rel}" href="{e(card["href"])}" rel="{rel}"><small>{word} book</small>'
                f'<strong>{e(card["name"])}</strong></a>')

    hub_href = f"/{canon}.html"
    main = f"""  {crumbs(b["crumbs"])}

  <header class="sp-head sp-book-head">
    <p class="sp-eyebrow"><a href="{hub_href}">{e(b["kicker"])}</a>{f' · <span>{e(group_title)}</span>' if group_title else ''}</p>
    <h1 class="sp-title">{e(name)}</h1>
    <p class="sp-lede">{e(b["subtitle"])}</p>
    <div class="sp-actions">
      {start}
      <a class="sp-btn" href="#" data-continue hidden></a>
    </div>
  </header>

  <section class="sp-section sp-chapters" aria-labelledby="chapterSelectTitle">
    <div class="sp-sec-head">
      <div>
        <h2 id="chapterSelectTitle">{e(b["panel_h2"])}</h2>
        <p>{e(b["panel_p"])}</p>
      </div>
      <span class="sp-count">{e(b["chapter_count_label"])}</span>
    </div>
    {notice}
    <ol class="sp-ch-grid" id="chapGrid" data-canon="{canon}" data-book="{e(slug)}" aria-label="{e(name)} chapters">
      {"".join(cells)}
    </ol>
  </section>

  <section class="sp-section sp-facts" aria-label="{e(b["identity_label"])}">
    <h2 class="sp-sec-title">About {e(name)}</h2>
    <dl class="sp-fact-list">{facts_html}</dl>
  </section>

  <nav class="sp-booknav" aria-label="{e(CANON_LABEL[canon])} books">
    {nav_link(prev_card, "prev", "Previous")}
    <a class="sp-booknav-all" href="{hub_href}">All {e(CANON_LABEL[canon])} books</a>
    {nav_link(next_card, "next", "Next")}
  </nav>"""
    return page(f'data-canon="{canon}" data-book="{e(slug)}"', b["title"], b["description"], main)


# ---------------------------------------------------------------- collection hubs
def render_hub(canon):
    hub = CONTENT["hubs"][canon]
    groups, _ = collection(canon)
    jump = "".join(f'<li><a href="#{slugify(g["h2"])}">{e(g["h2"])}</a></li>' for g in groups if g["books"])
    sections = []
    for i, g in enumerate(groups):
        gid = slugify(g["h2"])
        tiles = []
        for card in g["books"]:
            _, _, total = book_meta(book_key_from_href(card["href"]))
            chapters = f'{total} chapter{"s" if total != 1 else ""}'
            tiles.append(
                f'<li data-book-item data-name="{e(card["name"].lower())}" data-abbr="{e(re.sub("<[^>]+>", "", card["abbr"]).replace(chr(160), " ").lower())}">'
                f'<a class="sp-book" href="{e(card["href"])}">'
                f'<span class="sp-book-abbr" aria-hidden="true">{safe_abbr(card["abbr"])}</span>'
                f'<span class="sp-book-name">{e(card["name"])}</span>'
                f'<span class="sp-book-meta">{e(card["era"])}<span class="sp-book-ch"><span aria-hidden="true"> · </span><span class="sp-sr">, </span>{chapters}</span></span>'
                f'</a></li>')
        grid = f'<ul class="sp-book-grid" role="list">{"".join(tiles)}</ul>' if tiles else ""
        sections.append(f"""    <section class="sp-group{' is-note' if not tiles else ''}" id="{gid}" aria-labelledby="{gid}-h" data-book-group>
      <header class="sp-group-head">
        <span class="sp-group-count">{e(g["count"])}</span>
        <h2 id="{gid}-h">{e(g["h2"])}</h2>
        <p>{e(g["p"])}</p>
      </header>
      {grid}
    </section>""")
    main = f"""  {crumbs(hub["crumbs"])}

  <header class="sp-head sp-hub-head">
    <p class="sp-eyebrow">{e(hub["kicker"])}</p>
    <h1 class="sp-title">{e(hub["h1"])}</h1>
    <p class="sp-lede">{e(hub["subtitle"])}</p>
    <div class="sp-finder" role="search">
      <label class="sp-sr" for="bookFilter">Find a book in the {e(CANON_LABEL[canon])}</label>
      <input id="bookFilter" type="search" placeholder="Find a book…" autocomplete="off" enterkeyhint="search" data-book-filter/>
      <p class="sp-finder-status" aria-live="polite" data-filter-status></p>
    </div>
  </header>

  <nav class="sp-jump" aria-label="Sections">
    <ul>{jump}</ul>
  </nav>

  <div class="sp-groups" aria-label="{e(hub["guide_label"])}">
{chr(10).join(sections)}
    <p class="sp-empty" data-filter-empty hidden>No book matches that name. <a href="/biblia.html">Browse all of Biblia</a></p>
  </div>"""
    return page(f'data-canon="{canon}"', hub["title"], hub["description"], main)


# ---------------------------------------------------------------- Biblia hub
def render_biblia():
    hub = CONTENT["hubs"]["biblia"]
    collections = {"/tanakh.html": "tanakh", "/apocrypha.html": "apocrypha", "/newtestament.html": "newtestament"}
    scripture, tools = [], []
    for c in hub["cards"]:
        if c["href"] in collections:
            canon = collections[c["href"]]
            groups, books = collection(canon)
            first = books[0]
            scripture.append(f"""      <li class="sp-canon-card">
        <a class="sp-canon-link" href="{e(c["href"])}">
          <span class="sp-canon-thumb" aria-hidden="true">{e(c["thumb"])}</span>
          <span class="sp-card-kicker">{e(c["kicker"])}</span>
          <span class="sp-card-title">{e(c["title"])}</span>
          <span class="sp-card-desc">{e(c["desc"])}</span>
          <span class="sp-card-meta">{len(books)} books · {len([g for g in groups if g["books"]])} sections</span>
        </a>
        <a class="sp-canon-start" href="{e(first["href"])}">Begin with {e(first["name"])}</a>
      </li>""")
        else:
            tools.append(f"""      <li>
        <a class="sp-tool" href="{e(c["href"])}">
          <span class="sp-card-kicker">{e(c["kicker"])}</span>
          <span class="sp-card-title">{e(c["title"])}</span>
          <span class="sp-card-desc">{e(c["desc"])}</span>
          <span class="sp-tool-thumb" aria-hidden="true">{e(c["thumb"])}</span>
        </a>
      </li>""")
    stats = "".join(f'<div class="sp-stat"><dt>{e(s["label"])}</dt><dd>{e(s["value"])}</dd></div>' for s in hub["stats"])
    note = hub["note"]
    main = f"""  {crumbs(hub["crumbs"])}

  <header class="sp-head sp-biblia-head">
    <p class="sp-eyebrow">{e(hub["kicker"])}</p>
    <h1 class="sp-title">{e(hub["h1"])}</h1>
    <p class="sp-lede">{e(hub["subtitle"])}</p>
  </header>

  <aside class="sp-continue" aria-label="Continue reading" data-continue-reading hidden>
    <span class="sp-continue-label">Continue reading</span>
    <a class="sp-continue-link" href="#"><strong data-continue-title></strong><span data-continue-canon></span></a>
  </aside>

  <section class="sp-section sp-collections" aria-labelledby="spScripture">
    <h2 class="sp-sec-title" id="spScripture">Scripture</h2>
    <ul class="sp-canon-grid" role="list">
{chr(10).join(scripture)}
    </ul>
  </section>

  <section class="sp-section sp-intro" aria-label="Biblia overview">
    <div class="sp-intro-note">
      <span class="sp-card-kicker">{e(note["label"])}</span>
      <h2>{e(note["h2"])}</h2>
      <p>{e(note["p"])}</p>
    </div>
    <dl class="sp-stats" aria-label="Biblia quick stats">{stats}</dl>
  </section>

  <section class="sp-section sp-tools" aria-labelledby="spTools">
    <h2 class="sp-sec-title" id="spTools">Study tools</h2>
    <ul class="sp-tool-grid" role="list">
{chr(10).join(tools)}
    </ul>
  </section>"""
    # Biblia had no meta description, so search engines and the site search index fell back to raw page
    # text (including CSS). Use the page's own hero sentence instead.
    return page('data-hub="biblia"', hub["title"], hub["description"] or hub["subtitle"], main)


# ---------------------------------------------------------------- sharing metadata
SITE = "https://semiticjew.org"
SHARE_IMAGE = SITE + "/images/social-preview.png"


def with_share_meta(rel, html_text):
    """Canonical URL plus Open Graph / X cards, built from the page's own <title> and description."""
    title = html.unescape(re.search(r"<title>(.*?)</title>", html_text).group(1))
    m = re.search(r'<meta name="description" content="([^"]*)"/>', html_text)
    desc = html.unescape(m.group(1)) if m else ""
    url = f"{SITE}/{rel.as_posix()}"
    tags = [f'<link rel="canonical" href="{e(url)}"/>',
            f'<meta property="og:type" content="website"/>',
            f'<meta property="og:site_name" content="Semitic Jew"/>',
            f'<meta property="og:title" content="{e(title)}"/>',
            f'<meta property="og:url" content="{e(url)}"/>',
            f'<meta property="og:image" content="{SHARE_IMAGE}"/>',
            f'<meta name="twitter:card" content="summary_large_image"/>',
            f'<meta name="twitter:title" content="{e(title)}"/>',
            f'<meta name="twitter:image" content="{SHARE_IMAGE}"/>']
    if desc:
        tags[4:4] = [f'<meta property="og:description" content="{e(desc)}"/>']
        tags.append(f'<meta name="twitter:description" content="{e(desc)}"/>')
    anchor = "\n<script>/* Apply the saved theme"
    return html_text.replace(anchor, "\n" + "\n".join(tags) + anchor, 1)


# ---------------------------------------------------------------- build
def build():
    out = {Path("biblia.html"): render_biblia()}
    for canon in CANON_LABEL:
        out[Path(f"{canon}.html")] = render_hub(canon)
        groups, books = collection(canon)
        group_of = {b["href"]: g["h2"] for g in groups for b in g["books"]}
        for i, card in enumerate(books):
            key = book_key_from_href(card["href"])
            prev_card = books[i - 1] if i > 0 else None
            next_card = books[i + 1] if i < len(books) - 1 else None
            out[Path(key + ".html")] = render_book(key, prev_card, next_card, group_of.get(card["href"], ""))
    return {rel: with_share_meta(rel, text) for rel, text in out.items()}


def main():
    pages = build()
    assert len(pages) == 85, len(pages)
    stale = []
    for rel, html_text in pages.items():
        path = ROOT / rel
        if "--check" in sys.argv:
            if not path.exists() or path.read_text(encoding="utf-8") != html_text:
                stale.append(str(rel))
        else:
            path.write_text(html_text, encoding="utf-8")
    if "--check" in sys.argv:
        if stale:
            print("Out of date (run tools/build_scripture_pages.py):", ", ".join(stale[:10]), "…" if len(stale) > 10 else "")
            sys.exit(1)
        print(f"{len(pages)} pages up to date")
    else:
        print(f"wrote {len(pages)} pages")


if __name__ == "__main__":
    main()
